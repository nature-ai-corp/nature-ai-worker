"""Read-only S-C residue audit command for installer integration.

Run: python -m nature_worker.install_audit --sc-root PATH --mode-marker PATH

Exit codes:
  2 advisory result only (even when all supplied checks claim clean)
  3 invalid arguments or unreadable evidence

The evidence document must be generated by a trusted OS-specific installer
probe. Passing a handcrafted JSON file is not proof of enterprise compliance.
This utility NEVER deletes data or authorizes an installation by itself.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from .install_gate import CleanEvidence, standalone_install_decision
from .os_probes import local_os_diagnostics


def audit(sc_root: Path, mode_marker: Path, evidence_path: Path | None) -> dict:
    if evidence_path is None:
        checks = {
            name: None
            for name in (
                "os_credentials", "running_processes", "installed_packages",
                "other_app_locations", "device_policy",
            )
        }
    else:
        obj = json.loads(evidence_path.read_text(encoding="utf-8"))
        if not isinstance(obj, dict) or not isinstance(obj.get("checks"), dict):
            raise ValueError("Evidence must contain a 'checks' object.")
        checks = obj["checks"]
    decision = standalone_install_decision(
        sc_root, CleanEvidence(checks), mode_marker=mode_marker
    )
    return {
        "clean": False,  # never authorize install based on untrusted JSON
        "reported_checks_clean": decision.allowed,
        "installation_authorized": False,
        "blockers": list(decision.blockers),
        "notice": "Advisory only: a trusted OS installer must validate evidence "
                  "provenance, installation records and policy independently.",
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Read-only Platform Client residue audit.")
    parser.add_argument("--sc-root", type=Path, required=True)
    parser.add_argument("--mode-marker", type=Path, required=True)
    parser.add_argument("--host-diagnostics", action="store_true",
                        help="Add read-only best-effort OS diagnostics; never authorizes install.")
    parser.add_argument("--evidence", type=Path,
                        help="OS checks JSON from a trusted installer probe.")
    args = parser.parse_args(argv)
    try:
        result = audit(args.sc_root, args.mode_marker, args.evidence)
        if args.host_diagnostics:
            results = local_os_diagnostics((args.sc_root, args.mode_marker))
            result["os_diagnostics"] = [
                {"check": f.check, "clean": f.clean, "detail": f.detail}
                for f in results
            ]
            result["installation_authorized"] = False
            result["clean"] = False
    except (OSError, ValueError, TypeError) as exc:
        print(json.dumps({"clean": False, "error": str(exc)}), file=sys.stdout)
        return 3
    print(json.dumps(result))
    return 2  # installer authorization requires trusted OS probes, not this CLI


if __name__ == "__main__":
    raise SystemExit(main())
